// src/jobs/cron.js
import cron from 'node-cron';
import db from '../config/database.js';
import { ReportsService } from '../modules/reports/reports.service.js';
import { NotificationService } from '../modules/notifications/notifications.service.js';
import { logger } from '../utils/logger.js';

/**
 * تهيئة المهام المجدولة في النظام
 * توقيت اليمن (Asia/Aden: UTC+3)
 * أيام العمل: الأحد إلى الخميس (0, 1, 2, 3, 4)
 */
export function initCronJobs() {
  logger.info('⏰ Initializing scheduled cron jobs (Asia/Aden)...');

  // 1. إنشاء مسودة التقرير اليومي تلقائياً في نهاية دوام العمل (الساعة 17:00 من الأحد إلى الخميس)
  cron.schedule(
    '0 17 * * 0-4',
    async () => {
      logger.info('🤖 Starting automated daily report draft generation job...');
      try {
        const todayStr = new Date().toISOString().split('T')[0];

        // جلب جميع الموظفين النشطين
        const users = await db('users')
          .where({ is_active: 1 })
          .whereNull('deleted_at')
          .select('id', 'name', 'email', 'department_id');

        for (const user of users) {
          try {
            await ReportsService.autoGenerateDailyReport(user, todayStr);
          } catch (err) {
            logger.warn(`Failed to auto-generate report for user ${user.id}: ${err.message}`);
          }
        }
        logger.info(`✅ Auto-generated daily report drafts for ${users.length} users.`);
      } catch (error) {
        logger.error(`Daily report cron error: ${error.message}`);
      }
    },
    { timezone: 'Asia/Aden' }
  );

  // 2. فحص المهام التي اقترب موعد تسليمها أو تأخرت (يومياً الساعة 08:30 صباحاً)
  cron.schedule(
    '30 8 * * 0-4',
    async () => {
      logger.info('🔍 Checking overdue and upcoming tasks...');
      try {
        const todayStr = new Date().toISOString().split('T')[0];

        // المهام المتأخرة
        const overdueTasks = await db('tasks')
          .where('due_date', '<', todayStr)
          .whereNotIn('status', ['approved', 'cancelled'])
          .whereNull('deleted_at')
          .select('id', 'title', 'assigned_to', 'due_date');

        for (const task of overdueTasks) {
          if (task.assigned_to) {
            await NotificationService.notify({
              userId: task.assigned_to,
              type: 'task.overdue',
              title: 'تنبيه: مهمة متأخرة عن موعدها',
              body: `المهمة (${task.title}) تجاوزت موعد التسليم المحدد (${task.due_date}). يرجى سرعة إنهائها أو تحديث الحالة.`,
              relatedEntityType: 'task',
              relatedEntityId: task.id,
            });
          }
        }
      } catch (error) {
        logger.error(`Task reminder cron error: ${error.message}`);
      }
    },
    { timezone: 'Asia/Aden' }
  );
}
