// src/modules/reports/reports.routes.js
import { Router } from 'express';
import { ReportsController } from './reports.controller.js';
import { authenticate } from '../../middleware/auth.middleware.js';
import { validate } from '../../middleware/validate.middleware.js';
import {
  createReportSchema,
  updateReportSchema,
  autoGenerateReportSchema,
  reportApprovalSchema,
} from '../../validators/reports.validator.js';

const router = Router();

router.use(authenticate);

router.get('/', ReportsController.list);
router.post('/', validate(createReportSchema), ReportsController.create);
router.post('/auto-generate', validate(autoGenerateReportSchema), ReportsController.autoGenerateDaily);
router.get('/:id', ReportsController.getById);
router.put('/:id', validate(updateReportSchema), ReportsController.update);
router.post('/:id/submit', ReportsController.submit);
router.post('/:id/action', validate(reportApprovalSchema), ReportsController.approvalAction);
router.get('/:id/export/pdf', ReportsController.exportPdf);

export default router;
