// src/modules/reports/reports.controller.js
import { ReportsService } from './reports.service.js';

export class ReportsController {
  static async list(req, res, next) {
    try {
      const { type, status, page, limit } = req.query;
      const result = await ReportsService.listReports(req.user, {
        type,
        status,
        page: page ? Number(page) : 1,
        limit: limit ? Number(limit) : 20,
      });
      res.json({ success: true, data: result });
    } catch (error) {
      next(error);
    }
  }

  static async getById(req, res, next) {
    try {
      const report = await ReportsService.getReportById(req.params.id, req.user);
      res.json({ success: true, data: report });
    } catch (error) {
      next(error);
    }
  }

  static async autoGenerateDaily(req, res, next) {
    try {
      const { date } = req.body;
      const report = await ReportsService.autoGenerateDailyReport(req.user, date);
      res.status(201).json({
        success: true,
        data: report,
        message: 'تم إعداد مسودة التقرير اليومي بنجاح من بيانات المهام',
      });
    } catch (error) {
      next(error);
    }
  }

  static async create(req, res, next) {
    try {
      const report = await ReportsService.createReport(req.user, req.body);
      res.status(201).json({
        success: true,
        data: report,
        message: 'تم إنشاء مسودة التقرير بنجاح',
      });
    } catch (error) {
      next(error);
    }
  }

  static async update(req, res, next) {
    try {
      const report = await ReportsService.updateReport(req.params.id, req.user, req.body);
      res.json({
        success: true,
        data: report,
        message: 'تم تحديث مسودة التقرير بنجاح',
      });
    } catch (error) {
      next(error);
    }
  }

  static async submit(req, res, next) {
    try {
      const report = await ReportsService.submitReport(req.params.id, req.user);
      res.json({
        success: true,
        data: report,
        message: 'تم إرسال التقرير للمراجعة والاعتماد بنجاح',
      });
    } catch (error) {
      next(error);
    }
  }

  static async approvalAction(req, res, next) {
    try {
      const { action, notes } = req.body;
      const report = await ReportsService.handleApprovalAction(req.params.id, req.user, {
        action,
        notes,
      });
      const actionText =
        action === 'approve' ? 'اعتماد' : action === 'reject' ? 'رفض' : 'طلب تعديل';
      res.json({
        success: true,
        data: report,
        message: `تم ${actionText} التقرير بنجاح`,
      });
    } catch (error) {
      next(error);
    }
  }

  static async exportPdf(req, res, next) {
    try {
      const report = await ReportsService.getReportById(req.params.id, req.user);
      res.json({
        success: true,
        data: {
          report,
          org_name: 'مؤسسة بصمة للأعمال الإنسانية',
          generated_at: new Date().toISOString(),
        },
      });
    } catch (error) {
      next(error);
    }
  }
}
