// src/modules/reports/reports.service.js
import db from '../../config/database.js';
import { NotificationService } from '../notifications/notifications.service.js';

export class ReportsService {
  /**
   * جلب التقارير بحسب صلاحيات المستخدم
   */
  static async listReports(user, { type, status, page = 1, limit = 20 }) {
    const offset = (page - 1) * limit;

    let query = db('reports as r')
      .leftJoin('users as u', 'r.user_id', 'u.id')
      .leftJoin('departments as d', 'r.department_id', 'd.id')
      .whereNull('r.deleted_at')
      .select(
        'r.*',
        'u.name as user_name',
        'u.email as user_email',
        'd.name as department_name'
      );

    if (!user.isExecutive) {
      if (user.isDepartmentManager) {
        query = query.where('r.department_id', user.department_id);
      } else {
        query = query.where('r.user_id', user.id);
      }
    }

    if (type) query = query.where('r.type', type);
    if (status) query = query.where('r.status', status);

    const [{ total }] = await query.clone().count('r.id as total');

    const reports = await query
      .orderBy('r.period_start', 'desc')
      .limit(limit)
      .offset(offset);

    return {
      items: reports,
      pagination: {
        total: Number(total),
        page: Number(page),
        limit: Number(limit),
        totalPages: Math.ceil(Number(total) / limit),
      },
    };
  }

  /**
   * جلب تقرير محدد مع المهام المرتبطة به والمرفقات وسجل الاعتمادات
   */
  static async getReportById(id, user) {
    const report = await db('reports as r')
      .leftJoin('users as u', 'r.user_id', 'u.id')
      .leftJoin('departments as d', 'r.department_id', 'd.id')
      .where('r.id', id)
      .whereNull('r.deleted_at')
      .select(
        'r.*',
        'u.name as user_name',
        'u.email as user_email',
        'd.name as department_name'
      )
      .first();

    if (!report) {
      const error = new Error('التقرير غير موجود');
      error.statusCode = 404;
      throw error;
    }

    // التحقق من الصلاحيات
    if (!user.isExecutive) {
      if (user.isDepartmentManager && report.department_id !== user.department_id) {
        const error = new Error('غير مصرح لك بعرض تقرير خارج قسمك');
        error.statusCode = 403;
        throw error;
      }
      if (!user.isDepartmentManager && report.user_id !== user.id) {
        const error = new Error('غير مصرح لك بعرض تقرير خاص بموظف آخر');
        error.statusCode = 403;
        throw error;
      }
    }

    // جلب المهام المرتبطة
    const tasks = await db('report_tasks as rt')
      .join('tasks as t', 'rt.task_id', 't.id')
      .where({ 'rt.report_id': id })
      .select(
        't.id',
        't.title',
        't.status',
        't.completion_rate',
        't.priority',
        'rt.notes as report_notes'
      );

    // جلب المرفقات
    const attachments = await db('report_attachments as ra')
      .join('files as f', 'ra.file_id', 'f.id')
      .where({ 'ra.report_id': id })
      .select('f.*');

    // خطوات الاعتماد
    const approvalSteps = await db('approval_steps as a')
      .leftJoin('users as u', 'a.approver_id', 'u.id')
      .where({ entity_type: 'report', entity_id: id })
      .select('a.*', 'u.name as approver_name')
      .orderBy('a.step_order', 'asc');

    report.tasks = tasks;
    report.attachments = attachments;
    report.approval_steps = approvalSteps;

    return report;
  }

  /**
   * إنشاء مسودة تقرير يومي تلقائي من مهام اليوم
   * قابل للتكرار بشكل آمن (Idempotent) بدون تكرار
   */
  static async autoGenerateDailyReport(user, targetDate = null) {
    const dateStr = targetDate || new Date().toISOString().split('T')[0];

    // التحقق من وجود تقرير لنفس اليوم مسبقاً
    const existing = await db('reports')
      .where({
        user_id: user.id,
        type: 'daily',
        period_start: dateStr,
      })
      .whereNull('deleted_at')
      .first();

    if (existing) {
      return this.getReportById(existing.id, user);
    }

    // جلب مهام الموظف لهذا اليوم (سواء المكتملة أو قيد التنفيذ أو المستحقة اليوم)
    const todayTasks = await db('tasks')
      .where({ assigned_to: user.id })
      .whereNull('deleted_at')
      .where((b) => {
        b.where('due_date', dateStr)
          .orWhere('completed_at', '>=', `${dateStr} 00:00:00`)
          .orWhere('status', 'in_progress');
      })
      .select('id', 'title', 'status', 'completion_rate', 'priority');

    let tasksSummary = 'لا توجد مهام مسجلة لهذا اليوم.';
    if (todayTasks.length > 0) {
      tasksSummary = todayTasks
        .map(
          (t, i) =>
            `${i + 1}. ${t.title} [الحالة: ${t.status}] [الإنجاز: ${t.completion_rate}%]`
        )
        .join('\n');
    }

    const defaultContent = `تقرير العمل اليومي ليوم: ${dateStr}\n\nالموظف: ${user.name}\n\nالمهام المنجزة وقيد التنفيذ:\n${tasksSummary}\n\nأعمال إضافية / ملاحظات:\n(يمكنك إضافة تفاصيل إضافية هنا)`;

    let reportId;
    await db.transaction(async (trx) => {
      const [newId] = await trx('reports').insert({
        user_id: user.id,
        department_id: user.department_id,
        type: 'daily',
        title: `التقرير اليومي - ${dateStr} - ${user.name}`,
        period_start: dateStr,
        period_end: dateStr,
        content: defaultContent,
        is_auto_generated: 1,
        status: 'draft',
        created_at: new Date(),
        updated_at: new Date(),
      });

      reportId = newId;

      if (todayTasks.length > 0) {
        const reportTaskRows = todayTasks.map((t) => ({
          report_id: newId,
          task_id: t.id,
          notes: `حالة المهمة: ${t.status} - نسبة الإنجاز: ${t.completion_rate}%`,
        }));
        await trx('report_tasks').insert(reportTaskRows);
      }
    });

    return this.getReportById(reportId, user);
  }

  /**
   * إنشاء تقرير يدوي (أسبوعي / شهري)
   */
  static async createReport(user, data) {
    const existing = await db('reports')
      .where({
        user_id: user.id,
        type: data.type,
        period_start: data.period_start,
      })
      .whereNull('deleted_at')
      .first();

    if (existing) {
      const error = new Error('يوجد تقرير مسجل مسبقاً لهذه الفترة');
      error.statusCode = 409;
      throw error;
    }

    let reportId;
    await db.transaction(async (trx) => {
      const [newId] = await trx('reports').insert({
        user_id: user.id,
        department_id: user.department_id,
        type: data.type,
        title: data.title,
        period_start: data.period_start,
        period_end: data.period_end,
        content: data.content || null,
        is_auto_generated: 0,
        status: 'draft',
        created_at: new Date(),
        updated_at: new Date(),
      });

      reportId = newId;

      if (data.task_ids && data.task_ids.length > 0) {
        const rows = data.task_ids.map((tid) => ({
          report_id: newId,
          task_id: tid,
          notes: null,
        }));
        await trx('report_tasks').insert(rows);
      }
    });

    return this.getReportById(reportId, user);
  }

  /**
   * تعديل التقرير (مسودة فقط)
   */
  static async updateReport(id, user, data) {
    const report = await db('reports').where({ id }).whereNull('deleted_at').first();
    if (!report) {
      const error = new Error('التقرير غير موجود');
      error.statusCode = 404;
      throw error;
    }

    if (report.user_id !== user.id) {
      const error = new Error('يمكن لصاحب التقرير فقط تعديله');
      error.statusCode = 403;
      throw error;
    }

    if (report.status !== 'draft' && report.status !== 'revision_requested') {
      const error = new Error('لا يمكن تعديل التقرير بعد اعتماده أو إرساله للمراجعة');
      error.statusCode = 400;
      throw error;
    }

    await db.transaction(async (trx) => {
      const updateData = { updated_at: new Date() };
      if (data.title) updateData.title = data.title;
      if (data.content !== undefined) updateData.content = data.content;

      await trx('reports').where({ id }).update(updateData);

      if (data.task_ids) {
        await trx('report_tasks').where({ report_id: id }).delete();
        if (data.task_ids.length > 0) {
          const rows = data.task_ids.map((tid) => ({
            report_id: id,
            task_id: tid,
            notes: null,
          }));
          await trx('report_tasks').insert(rows);
        }
      }
    });

    return this.getReportById(id, user);
  }

  /**
   * إرسال التقرير للمراجعة والاعتماد
   */
  static async submitReport(id, user) {
    const report = await db('reports').where({ id }).whereNull('deleted_at').first();
    if (!report) {
      const error = new Error('التقرير غير موجود');
      error.statusCode = 404;
      throw error;
    }

    if (report.user_id !== user.id) {
      const error = new Error('يمكن لصاحب التقرير فقط إرساله للمراجعة');
      error.statusCode = 403;
      throw error;
    }

    if (report.status !== 'draft' && report.status !== 'revision_requested') {
      const error = new Error('التقرير مرسل مسبقاً أو معتمد');
      error.statusCode = 400;
      throw error;
    }

    // تحديد المعتمد:
    let nextApproverId = null;
    const department = report.department_id
      ? await db('departments').where({ id: report.department_id }).first()
      : null;

    const executiveUser = await db('user_roles as ur')
      .join('roles as r', 'ur.role_id', 'r.id')
      .where('r.name', 'executive_director')
      .select('ur.user_id')
      .first();

    const edId = executiveUser ? executiveUser.user_id : null;

    if (user.isExecutive) {
      // إعفاء إداري موثق للمدير التنفيذي لمنع الاعتماد الذاتي
      nextApproverId = null;
    } else if (department && department.manager_id && department.manager_id !== user.id) {
      nextApproverId = department.manager_id;
    } else {
      nextApproverId = edId;
    }

    await db.transaction(async (trx) => {
      if (user.isExecutive) {
        await trx('reports').where({ id }).update({
          status: 'approved',
          submitted_at: new Date(),
          approved_at: new Date(),
          updated_at: new Date(),
        });
        await trx('approval_steps').insert({
          entity_type: 'report',
          entity_id: id,
          step_order: 1,
          approver_id: user.id,
          status: 'approved',
          notes: 'اعتماد إداري ذاتي للمدير التنفيذي (إعفاء موثق)',
          acted_at: new Date(),
        });
      } else {
        await trx('reports').where({ id }).update({
          status: 'under_review',
          submitted_at: new Date(),
          updated_at: new Date(),
        });

        if (nextApproverId) {
          await trx('approval_steps').insert({
            entity_type: 'report',
            entity_id: id,
            step_order: 1,
            approver_id: nextApproverId,
            status: 'pending',
          });

          await NotificationService.notify({
            userId: nextApproverId,
            type: 'report.submitted',
            title: 'تقرير جديد بانتظار المراجعة والاعتماد',
            body: `قام ${user.name} بإرسال (${report.title}) لمراجعتها واعتمادها.`,
            relatedEntityType: 'report',
            relatedEntityId: id,
          });
        }
      }
    });

    return this.getReportById(id, user);
  }

  /**
   * اعتماد أو رفض أو إعادة التقرير للتعديل
   */
  static async handleApprovalAction(id, approver, { action, notes }) {
    const report = await db('reports as r')
      .leftJoin('users as u', 'r.user_id', 'u.id')
      .where('r.id', id)
      .whereNull('r.deleted_at')
      .select('r.*', 'u.name as owner_name')
      .first();

    if (!report) {
      const error = new Error('التقرير غير موجود');
      error.statusCode = 404;
      throw error;
    }

    if (report.user_id === approver.id) {
      const error = new Error('لا يجوز للمستخدم اعتماد تقريره الشخصي');
      error.statusCode = 403;
      throw error;
    }

    if (report.status !== 'under_review') {
      const error = new Error('التقرير ليس قيد المراجعة حالياً');
      error.statusCode = 400;
      throw error;
    }

    const pendingStep = await db('approval_steps')
      .where({
        entity_type: 'report',
        entity_id: id,
        approver_id: approver.id,
        status: 'pending',
      })
      .first();

    if (!pendingStep && !approver.isExecutive) {
      const error = new Error('لست المعتمد المعين لهذه الخطوة');
      error.statusCode = 403;
      throw error;
    }

    await db.transaction(async (trx) => {
      const stepId = pendingStep ? pendingStep.id : null;
      if (stepId) {
        await trx('approval_steps').where({ id: stepId }).update({
          status: action === 'approve' ? 'approved' : action === 'reject' ? 'rejected' : 'revision_requested',
          notes: notes || null,
          acted_at: new Date(),
        });
      }

      if (action === 'request_revision') {
        await trx('reports').where({ id }).update({
          status: 'revision_requested',
          updated_at: new Date(),
        });

        await NotificationService.notify({
          userId: report.user_id,
          type: 'report.revision_requested',
          title: 'إعادة التقرير للتعديل',
          body: `طلب ${approver.name} تعديل التقرير (${report.title}): ${notes}`,
          relatedEntityType: 'report',
          relatedEntityId: id,
        });
      } else if (action === 'reject') {
        await trx('reports').where({ id }).update({
          status: 'rejected',
          updated_at: new Date(),
        });

        await NotificationService.notify({
          userId: report.user_id,
          type: 'report.rejected',
          title: 'تم رفض التقرير',
          body: `تم رفض التقرير (${report.title}) من قبل ${approver.name}. السبب: ${notes}`,
          relatedEntityType: 'report',
          relatedEntityId: id,
        });
      } else if (action === 'approve') {
        const isLastStep = approver.isExecutive;

        if (isLastStep) {
          await trx('reports').where({ id }).update({
            status: 'approved',
            approved_at: new Date(),
            updated_at: new Date(),
          });

          await NotificationService.notify({
            userId: report.user_id,
            type: 'report.approved',
            title: 'تم اعتماد تقريرك نهائياً',
            body: `تم اعتماد التقرير (${report.title}) بنجاح.`,
            relatedEntityType: 'report',
            relatedEntityId: id,
          });
        } else {
          // تصعيد للمدير التنفيذي
          const executiveUser = await trx('user_roles as ur')
            .join('roles as r', 'ur.role_id', 'r.id')
            .where('r.name', 'executive_director')
            .select('ur.user_id')
            .first();

          if (executiveUser) {
            await trx('approval_steps').insert({
              entity_type: 'report',
              entity_id: id,
              step_order: 2,
              approver_id: executiveUser.user_id,
              status: 'pending',
            });

            await NotificationService.notify({
              userId: executiveUser.user_id,
              type: 'report.submitted',
              title: 'تقرير معتمد من مدير القسم بانتظار اعتمادك النهائي',
              body: `اعتمد مدير القسم ${approver.name} تقرير الموظف (${report.owner_name}) وبانتظار موافقتك.`,
              relatedEntityType: 'report',
              relatedEntityId: id,
            });
          }
        }
      }
    });

    return this.getReportById(id, approver);
  }
}
